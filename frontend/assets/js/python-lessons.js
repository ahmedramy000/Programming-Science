// بيبني بانل كود بسيط للعرض بس (مش قابل للتشغيل) — بنفس شكل بانلات الكود التانية
// في الموقع، لكن من غير زرار "تشغيل" عشان محرك الكود الأساسي (addCodePanel)
// بينفّذ أي كود كـJavaScript فعليًا، وده غلط لو الكود بايثون. وبرضه عشان
// الكود فيه حروف عربي + إنجليزي مع بعض، بنثبّت اتجاهه LTR صراحة عشان العلامات
// (الأقواس والتنصيص) متتلخبطش بسبب اتجاه الصفحة العام RTL.
function codeBlock(code) {
  const lines = code.split('\n').map((l) => l.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'));
  return `<div class="eng-ide" style="margin-top:8px;">
    <div class="eng-ide-tabbar"><span class="eng-ide-qlabel" style="color:#e0b65c;">Python</span></div>
    <div class="eng-ide-body" style="direction:ltr; text-align:left;">
      ${lines.map((ln, i) => `<div class="eng-ide-line"><span class="eng-ide-gutter">${i + 1}</span><span class="eng-ide-code">${ln || ' '}</span></div>`).join('')}
    </div>
  </div>`;
}

